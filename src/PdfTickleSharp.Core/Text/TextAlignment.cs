namespace PdfTickleSharp.Core.Text;

/// <summary>
/// Defines text alignment options for PDF text rendering.
/// </summary>
public enum TextAlignment
{
    /// <summary>
    /// Left-aligned text.
    /// </summary>
    Left,

    /// <summary>
    /// Center-aligned text.
    /// </summary>
    Center,

    /// <summary>
    /// Right-aligned text.
    /// </summary>
    Right,

    /// <summary>
    /// Justified text (both left and right margins aligned).
    /// </summary>
    Justified
} 